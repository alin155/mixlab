#!/usr/bin/env node
/**
 * 安装本地 Git 护栏（每个克隆/每台机器执行一次）：
 *   node scripts/dev/install-hooks.mjs
 *
 * 安装：
 * - pre-commit：越界文件拦截（按当前分支角色）
 * - pre-push：落后远端/merge commit/越界/共享未同步拦截
 *
 * 卸载：node scripts/dev/install-hooks.mjs --uninstall
 */
import { chmod, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";

function git(args) {
  return execFileSync("git", args, { encoding: "utf8", trim: true }).trim();
}

const repoRoot = git(["rev-parse", "--show-toplevel"]);
process.chdir(repoRoot);
const hooksDir = path.resolve(repoRoot, git(["rev-parse", "--git-path", "hooks"]));
const uninstall = process.argv.includes("--uninstall");
const preCommit = "#!/bin/sh\n# MixLab guard: generated by scripts/dev/install-hooks.mjs\nnode scripts/dev/scope-check.mjs --staged || exit 1\n";
const prePush = "#!/bin/sh\n# MixLab guard: generated by scripts/dev/install-hooks.mjs\nexec node scripts/dev/pre-push-guard.mjs\n";

async function writeHook(name, content) {
  const target = path.join(hooksDir, name);
  await writeFile(target, content, "utf8");
  await chmod(target, 0o755);
  console.log("installed " + name + " -> " + target);
}

async function main() {
  await mkdir(hooksDir, { recursive: true });
  if (uninstall) {
    for (const name of ["pre-commit", "pre-push"]) {
      const target = path.join(hooksDir, name);
      try {
        const current = await readFile(target, "utf8");
        if (current.includes("MixLab guard: generated by scripts/dev/install-hooks.mjs")) {
          await rm(target);
          console.log("removed " + name);
        } else {
          console.log("skip " + name + " (not installed by us)");
        }
      } catch {
        console.log("skip " + name + " (not found)");
      }
    }
    return;
  }
  await writeHook("pre-commit", preCommit);
  await writeHook("pre-push", prePush);
  console.log("");
  console.log("Guards active for: " + repoRoot);
  console.log("提示：不要用 --no-verify 绕过；共享内容请用 node scripts/dev/shared-sync.mjs --apply。");
}

main().catch((error) => {
  console.error("install-hooks failed:", error instanceof Error ? error.message : error);
  process.exit(1);
});
